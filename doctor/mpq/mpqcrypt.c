typedef struct {
    int16_t next[ITEMS + 1], prev[ITEMS + 1], parent[ITEMS + 1], child[ITEMS + 1];
    uint32_t weight[ITEMS + 1];
    uint16_t value[ITEMS + 1];
    int16_t by_byte[258];
    int used;
} tree;

static void remove_item(tree *t, int i) {                     /* RemoveItem (huff.cpp:415) */
    if (t->next[i] != NONE) {
        int a = t->prev[i], p = t->next[i];
        t->next[a] = (int16_t)p;
        t->prev[p] = (int16_t)a;
        t->next[i] = t->prev[i] = NONE;
    }
}

static void link_items(tree *t, int a, int b) {               /* LinkTwoItems (:451): b right after a */
    int n = t->next[a];
    t->next[b] = (int16_t)n;
    t->prev[b] = t->prev[n];
    t->prev[n] = (int16_t)b;
    t->next[a] = (int16_t)b;
}

static int higher_or_equal(tree *t, int i, uint32_t w) {      /* FindHigherOrEqualItem (:480) */
    if (i != NONE)
        for (; i != HEAD; i = t->prev[i])
            if (t->weight[i] >= w)
                return i;
    return HEAD;
}

