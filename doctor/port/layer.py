def part_path(fname):
    if os.path.isabs(fname):
        return fname
    if fname.startswith('KK:'):
        return os.path.join(KK_COMPAT, *fname[3:].split('/'))
    if fname.startswith('KKN:'):
        return os.path.join(KK_COMPAT, *fname[4:].split('/'))
    _demand_check()
    if fname.startswith('out/'):
        return os.path.join(OUT, *fname[4:].split('/'))
    return os.path.join(COMPAT, *fname.split('/'))


def part_names(p):
    return tuple(p) if isinstance(p, (tuple, list)) else (p,)


def display_name(p):
    n = part_names(p)[0]
    return n[4:] if n.startswith('KKN:') else n[3:] if n.startswith('KK:') else n


def kk_files():
    out = []
    for p in PARTES + WAVE1_PARTS:
        for n in part_names(p):
            if n.startswith('KK:') or n.startswith('KKN:'):
                out.append(part_path(n))
    return out


def read_parameters(latin1=True):
    _demand_check()
    if not os.path.isfile(PARAMETROS):
        return {}
    raw_bytes = json.load(open(PARAMETROS, encoding='utf-8'))
    params = {}
    for k, v in raw_bytes.items():
        if k.startswith('_'):
            continue
        if not re.match(r'^KK_[A-Z0-9_]+$', k) or not isinstance(v, str) or '"' in v or '\n' in v or '\r' in v:
            raise SystemExit('ABORT: invalid parameter in %s: %r' % (PARAMETROS, k))
        params[k] = v.encode('utf-8').decode('latin-1') if latin1 else v
    return params


def apply_parameters(body_text, origin, params, in_use=None):
    def swap(m):
        k = m.group(1)
        if k not in params:
            raise SystemExit('ABORT: %s asks for {{%s}} and %s does not have that value' % (origin, k, PARAMETROS))
        if in_use is not None:
            in_use.add(k)
        return params[k]
    return RX_PARAM.sub(swap, body_text)


def include_path(fname):
    _demand_check()
    return os.path.join(COMPAT, 'kk_%s.j' % fname)


def apply_includes(body_text, origin, ler):
    def swap(m):
        cpath = include_path(m.group(1))
        if not os.path.isfile(cpath):
            raise SystemExit(
                'ABORT: %s asks for the map section %s, which does not exist (each map declares each point; '
                'nothing to do, the file exists EMPTY)' % (origin, cpath)
            )
        t = ler(cpath)
        if t and not t.endswith('\n'):
            raise SystemExit('ABORT: the snippet %s does not end in a line break' % cpath)
        if RX_INCLUDE.search(t):
            raise SystemExit('ABORT: section %s has another inclusion (no inclusion inside a section)' % cpath)
        return t
    return RX_INCLUDE.sub(swap, body_text)


def apply_conditionals(body_text, origin, params, in_use=None):
    if '{{KK_SE:' not in body_text and '{{KK_FIMSE:' not in body_text:
        return body_text
    out = []
    pos = 0
    aberto = None
    for m in RX_IF.finditer(body_text):
        kind, fname = m.group(1), m.group(2)
        if kind == 'SE':
            if aberto:
                raise SystemExit('ABORT: %s: //{{KK_SE:%s}} inside the block //{{KK_SE:%s}}' % (origin, fname, aberto))
            aberto = fname
            out.append(body_text[pos:m.start()])
        else:
            if aberto != fname:
                raise SystemExit(
                    'ABORT: %s: //{{KK_FIMSE:%s}} without the //{{KK_SE:%s}} open' % (origin, fname, fname)
                )
            if in_use is not None and fname in params:
                in_use.add(fname)
            if params.get(fname) == 'true':
                out.append(body_text[pos:m.start()])
            aberto = None
        pos = m.end()
    if aberto:
        raise SystemExit('ABORT: %s: //{{KK_SE:%s}} without the //{{KK_FIMSE:%s}}' % (origin, aberto, aberto))
    out.append(body_text[pos:])
    t = ''.join(out)
    if '{{KK_SE:' in t or '{{KK_FIMSE:' in t:
        raise SystemExit('ABORT: %s: conditional block marker outside a line of its own' % origin)
    return t


def layer_files():
    _demand_check()
    from_project = sorted(os.listdir(COMPAT)) if os.path.isdir(COMPAT) else []
    return [os.path.join(COMPAT, f) for f in from_project if f.endswith('.j')] + kk_files()


def _read_utf8(file_path):
    return open(file_path, 'rb').read().decode('utf-8', 'surrogateescape')


def read_part_utf8(file_path, params=None):
    params = read_parameters(latin1=False) if params is None else params
    t = apply_includes(_read_utf8(file_path), file_path, _read_utf8)
    t = apply_conditionals(t, file_path, params)
    return apply_parameters(t, file_path, params)


def arg(fname, default_value=None, argv=None):
    for a in (sys.argv if argv is None else argv):
        if a.startswith('--' + fname + '='):
            return a[len(fname) + 3:]
    return default_value


