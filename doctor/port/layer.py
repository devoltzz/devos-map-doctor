def read_latin1(p):
    return open(p, 'rb').read().decode('latin-1').replace('\r\n', '\n')


def types_of(takes):
    if takes.strip() in ('nothing', ''):
        return []
    return [p.strip().split()[0] for p in takes.split(',')]


def jass_signature(fname, takes, ret):
    types = types_of(takes)
    if not types:
        return 'function %s takes nothing returns %s' % (fname, ret)
    return 'function %s takes %s returns %s' % (
        fname, ', '.join('%s a%d' % (t, i + 1) for i, t in enumerate(types)), ret)


def make_stubs(decl, order, implemented, heading=None):
    pend = [n for n in order if n not in implemented]
    L = []
    A = L.append
    A('// ==============================================================================================')
    if heading:
        A('// %s' % heading)
    else:
        A('// PART 3 -- STUBS: %d natives declared in the map that still have NO body.' % len(pend))
    A('//')
    A('// EXACT signature copied from the declaration in `war3map.j`. Empty body: it is what the platform')
    A('// would do with a native it does not know. Injected by `%s`.' % os.path.basename(GENERATOR))
    A('// ==============================================================================================')
    A('')
    if any(decl[n]['ret'] == 'code' for n in pend):
        A('function KK_codigo_vazio takes nothing returns nothing')
        A('endfunction')
        A('')
    for n in pend:
        d = decl[n]
        A(jass_signature(n, d['takes'], d['ret']))
        neutral_value = {'integer': '0', 'real': '0.0', 'boolean': 'false', 'string': '""'}.get(d['ret'])
        if d['ret'] == 'nothing':
            A('endfunction')
        elif neutral_value is not None:
            A('    return %s' % neutral_value)
            A('endfunction')
        elif d['ret'] == 'code':
            A('    return function KK_codigo_vazio')
            A('endfunction')
        else:
            A('    return null')
            A('endfunction')
        A('')
    return '\n'.join(L)


RX_GLOBAL = re.compile(
    r'^\s*(constant\s+)?(integer|real|boolean|string|handle|code|hashtable|timer|trigger|group|'
    r'force|region|rect|unit|item|player|effect|ability|destructable|dialog|button|lightning|widget|location|'
    r'image|texttag|ubersplat|sound|quest|questitem|defeatcondition|timerdialog|leaderboard|'
    r'multiboard|multiboarditem|trackable|framehandle|originframetype|framepointtype|'
    r'frameeventtype|textaligntype|oskeytype|eventid|eventtype|playerevent|playerunitevent|'
    r'unitevent|widgetevent|dialogevent|unitstate|abilityreallevelfield|abilityintegerlevelfield|'
    r'abilitystringlevelfield|abilitybooleanlevelfield|unitrealfield|unitintegerfield|'
    r'unitstringfield|unitbooleanfield|itemrealfield|itemintegerfield|itemstringfield|'
    r'limitop)\s+(array\s+)?[A-Za-z_]\w*\s*(=[^\r\n]*)?$')


RX_FUNC_DEF = re.compile(r'(?m)^function\s+([A-Za-z_]\w*)\s+takes')
RX_CALL = re.compile(r'(?<![\w.])([A-Za-z_]\w*)\s*\(|(?<![\w.])function\s+([A-Za-z_]\w*)')


def sort_by_dependency(body_text, already_defined):
    block_list = []
    pos = 0
    for m in RX_FUNC_DEF.finditer(body_text):
        fname = m.group(1)
        first_pos = body_text.rfind('\n', 0, m.start()) + 1
        end_pos = body_text.find('\nendfunction', m.end())
        if end_pos < 0:
            continue
        end_pos += len('\nendfunction')
        block_list.append((fname, first_pos, end_pos))
    if not block_list:
        return body_text, 0
    head_text = body_text[:block_list[0][1]]
    tail = body_text[block_list[-1][2]:]
    bodies = {}
    order = []
    for fname, i, f in block_list:
        if fname in bodies:
            continue
        bodies[fname] = body_text[i:f]
        order.append(fname)
    deps = {}
    for fname in order:
        d = set()
        body_without_decl = bodies[fname].split('\n', 1)[1] if '\n' in bodies[fname] else ''
        for m in RX_CALL.finditer(body_without_decl):
            tgt = m.group(1) or m.group(2)
            if tgt != fname and tgt in bodies:
                d.add(tgt)
        deps[fname] = d
    output = []
    done = set()
    remaining_names = list(order)
    while remaining_names:
        progress = False
        for fname in list(remaining_names):
            if all((x in done) or (x in already_defined) for x in deps[fname]):
                output.append(fname)
                done.add(fname)
                remaining_names.remove(fname)
                progress = True
        if not progress:
            chosen_name = min(remaining_names, key=lambda n: (len([x for x in deps[n] if x not in done]),
                                                              order.index(n)))
            print('WARNING: dependency cycle -- broken at %s' % chosen_name)
            output.append(chosen_name)
            done.add(chosen_name)
            remaining_names.remove(chosen_name)
    new = head_text + '\n\n'.join(bodies[n] for n in output) + '\n' + tail
    return new, len(order)


def implemented_names(*texts):
    matches = set()
    for t in texts:
        matches |= set(re.findall(r'(?m)^function\s+([A-Za-z_]\w*)\s+takes', t))
    return matches


def declaracoes(body_text):
    d = {}
    for m in RX_SIGNATURE.finditer(body_text):
        d[m.group(1)] = {'takes': m.group(2), 'ret': m.group(3)}
    return d


def called_names(body_text):
    matches = set()
    for m in RX_CALL.finditer(body_text):
        n = m.group(1) or m.group(2)
        if n not in KW_JASS:
            matches.add(n)
    return matches


def smoke_stubs(map_decl, order, in_layer, functions_text, map_txt, engine):
    A = [n for n in order if n not in in_layer]
    real_blocks = declaracoes(functions_text)
    called = called_names(map_txt)
    B = sorted(n for n in called
               if n in real_blocks and n not in set(A) and n not in engine)
    t1 = ('SMOKE (A) -- %d natives DECLARED by the map: EXACT signature, neutral body.'
          % len(A))
    t2 = ('SMOKE (B) -- %d functions of the layer that `war3map.j` CALLS: neutral body.' % len(B))
    return (make_stubs(map_decl, A, set(), t1) + '\n\n' + make_stubs(real_blocks, B, set(), t2),
            sorted(A), B)


def write_layer(file_path, natives, globals_txt, functions_txt, score):
    L = [line % {'score': score} if '%(score)s' in line else line
         for line in (LAYER_HEADER or default_layer_header())]
    for hash_key, body_text in (('natives', natives), ('globals_block', globals_txt), ('functions', functions_txt)):
        begin, end_pos = MARKS[hash_key]
        L.append(begin)
        L.append(body_text)
        L.append(end_pos)
    if not os.path.isdir(os.path.dirname(os.path.abspath(file_path))):
        os.makedirs(os.path.dirname(os.path.abspath(file_path)))
    raw_bytes = ('\n'.join(L) + '\n').encode('latin-1', 'replace')
    open(file_path, 'wb').write(raw_bytes)
    return raw_bytes


def map_native_declarations(origin):
    map_path = open(origin, 'rb').read().decode('utf-8', 'surrogateescape')
    map_path = re.sub(r'\r(?!\n)', '\n', map_path)
    decl = {}
    order = []
    for m in re.finditer(r'(?m)^\s*native\s+([A-Za-z_]\w*)\s+takes\s+(.*?)\s+returns\s+(\w+)', map_path):
        decl[m.group(1)] = {'takes': m.group(2).strip(), 'ret': m.group(3)}
        order.append(m.group(1))
    return decl, order


def _variable_name(ln):
    return ln.split('//')[0].split('=')[0].split()[-1]


def filter_conditional_natives(body_text, origin, decl, engine=()):
    bodies = {}
    rest = []
    pos = 0
    for m in RX_FUNC_DEF.finditer(body_text):
        if m.start() < pos:
            continue
        end_pos = body_text.find('\nendfunction', m.end())
        if end_pos < 0:
            raise SystemExit('ABORT: %s: function %s has no endfunction' % (origin, m.group(1)))
        end_pos += len('\nendfunction')
        rest.append(body_text[pos:m.start()])
        bodies.setdefault(m.group(1), body_text[m.start():end_pos])
        pos = end_pos
    rest.append(body_text[pos:])
    vars_ = [line.strip() for line in ''.join(rest).split('\n') if RX_GLOBAL.match(line.split('//')[0].rstrip())]
    entra = set()
    for n, body in bodies.items():
        if n not in decl or n in engine:
            continue
        a = RX_SIGNATURE.search(body)
        if not a or types_of(a.group(2)) != types_of(decl[n]['takes']) or a.group(3) != decl[n]['ret']:
            print('WARNING: %s: %s has another signature in the map (takes %s returns %s): the stub stays'
                  % (os.path.basename(origin), n, decl[n]['takes'], decl[n]['ret']))
            continue
        entra.add(n)
    work_queue = list(entra)
    while work_queue:
        n = work_queue.pop()
        for m in RX_CALL.finditer(bodies[n].split('\n', 1)[1]):
            tgt = m.group(1) or m.group(2)
            if tgt in bodies and tgt not in entra and tgt not in decl:
                entra.add(tgt)
                work_queue.append(tgt)
    if not entra:
        return ''
    used = '\n'.join(bodies[n] for n in entra)
    output = [line for line in vars_ if re.search(r'\b%s\b' % re.escape(_variable_name(line)), used)]
    output += [bodies[n] for n in bodies if n in entra]
    return '\n'.join(output) + '\n'


def _defined_in_fixed_parts(listing, params):
    name_list = set()
    for p in listing:
        for n in part_names(p):
            file_path = part_path(n)
            if n.startswith('KKN:') or not os.path.isfile(file_path):
                continue
            body_text = apply_includes(read_latin1(file_path), file_path, read_latin1)
            name_list |= implemented_names(apply_conditionals(body_text, file_path, params))
    return name_list


def read_parts(argv=None):
    _demand_check()
    listing = PARTES + (WAVE1_PARTS if '--onda1' in (sys.argv if argv is None else argv) else [])
    params = read_parameters()
    in_use = set()
    natives, globals_block, functions = [], [], []
    map_decl = engine_ref = None
    for p in listing:
        texts = []
        for n in part_names(p):
            file_path = part_path(n)
            if not os.path.isfile(file_path):
                print('WARNING: missing %s (empty part)' % file_path)
                continue
            body_text = apply_includes(read_latin1(file_path), file_path, read_latin1)
            body_text = apply_conditionals(body_text, file_path, params, in_use)
            body_text = apply_parameters(body_text, file_path, params, in_use)
            if n.startswith('KKN:'):
                if map_decl is None:
                    map_decl = map_native_declarations(arg('source', war3map_source(), argv))[0]
                    map_decl = dict((k, v) for k, v in map_decl.items() if k not in NO_STUB)
                    engine_ref = set(RX_ANY_DEF.findall(read_latin1(os.path.join(REF, 'common.j'))))
                    engine_ref |= set(RX_ANY_DEF.findall(read_latin1(os.path.join(REF, 'blizzard.j'))))
                    engine_ref |= _defined_in_fixed_parts(listing, params)
                body_text = filter_conditional_natives(body_text, file_path, map_decl, engine_ref)
                engine_ref |= implemented_names(body_text)
            texts.append(body_text)
        if not texts or (not any(texts) and any(n.startswith('KKN:') for n in part_names(p))):
            continue
        t = ''.join(texts)
        while '//@SLOTGLOBALS' in t and '//@ENDSLOTGLOBALS' in t:
            i = t.index('//@SLOTGLOBALS')
            j = t.index('//@ENDSLOTGLOBALS')
            globals_block += [line.strip() for line in t[i + len('//@SLOTGLOBALS'):j].split('\n') if line.strip()]
            t = t[:i] + t[j + len('//@ENDSLOTGLOBALS'):]
        while '//@GLOBALS' in t and '//@ENDGLOBALS' in t:
            i = t.index('//@GLOBALS')
            j = t.index('//@ENDGLOBALS')
            globals_block += [line.strip() for line in t[i + 10:j].split('\n') if line.strip()]
            t = t[:i] + t[j + 13:]
        body = []
        for line in t.split('\n'):
            s = line.strip()
            if s.startswith('native ') or s.startswith('constant native '):
                natives.append(s)
                continue
            no_comment = line.split('//')[0].rstrip() if '//' in line else line
            if RX_GLOBAL.match(no_comment):
                globals_block.append(no_comment.strip() if no_comment.strip() else s)
            else:
                body.append(line)
        functions.append('// ===== %s =====' % display_name(p))
        functions += body
    leftover = sorted(set(params) - in_use)
    if leftover:
        raise SystemExit('ABORT: %s has a value that no part asks for: %s' % (PARAMETROS, ', '.join(leftover)))
    return natives, globals_block, functions


def natives_of_map():
    _demand_check()
    if not os.path.isfile(MAP_NATIVES):
        return set()
    t = open(MAP_NATIVES, 'rb').read().decode('latin-1')
    return set(re.findall(r'(?m)^\s*native\s+([A-Za-z_]\w*)\s+takes\s', t))


